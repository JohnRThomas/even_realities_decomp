const uint8_t *font8x8_glyph(char c)
{
	if (c >= 'a' && c <= 'z') {
		c = (char)(c - 'a' + 'A');
	}
	if (c >= '0' && c <= '9') {
		static const uint8_t *const digits[10] = {
			glyph_0, glyph_1, glyph_2, glyph_3, glyph_4,
			glyph_5, glyph_6, glyph_7, glyph_8, glyph_9,
		};
		return digits[c - '0'];
	}
	if (c >= 'A' && c <= 'Z') {
		static const uint8_t *const letters[26] = {
			glyph_A, glyph_B, glyph_C, glyph_D, glyph_E,
			glyph_F, glyph_G, glyph_H, glyph_I, glyph_J,
			glyph_K, glyph_L, glyph_M, glyph_N, glyph_O,
			glyph_P, glyph_Q, glyph_R, glyph_S, glyph_T,
			glyph_U, glyph_V, glyph_W, glyph_X, glyph_Y,
			glyph_Z,
		};
		return letters[c - 'A'];
	}
	switch (c) {
	case ' ':
		return glyph_space;
	case '%':
		return glyph_percent;
	case '+':
		return glyph_plus;
	case ',':
		return glyph_comma;
	case '-':
		return glyph_minus;
	case '.':
		return glyph_dot;
	case '/':
		return glyph_slash;
	case ':':
		return glyph_colon;
	case '=':
		return glyph_equals;
	default:
		return glyph_box;
	}
}
